-- Migration: bảng REQUEST (yêu cầu vật tư)
-- Chạy trong Supabase SQL Editor trước khi dùng màn hình Request.
-- Mỗi dòng = 1 mã vật tư trong 1 request. Các dòng cùng 1 request dùng chung nhom_id.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS public.request (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nhom_id       uuid        NOT NULL DEFAULT gen_random_uuid(), -- mã nhóm request (1 lần thêm = 1 nhóm)
    thoi_gian     date        NOT NULL DEFAULT CURRENT_DATE,      -- Thời Gian
    psr           text        NULL,                               -- PSR (người yêu cầu)
    ma_vt         text        NOT NULL,                           -- Code (tham chiếu san_pham.ma_vt)
    ten_vt        text        NULL,                               -- Code Name (lưu kèm, hiển thị lấy từ san_pham)
    so_luong      numeric     NOT NULL DEFAULT 0,                 -- Số lượng
    ton_kho       numeric     NULL DEFAULT 0,                     -- Tồn kho tại thời điểm đề xuất
    kha_dung      numeric     NULL DEFAULT 0,                     -- Khả dụng tại thời điểm đề xuất
    ngay_su_dung  date        NOT NULL,                           -- Ngày Sử Dụng
    hoi_nghi      text        NULL,                               -- Hội Nghị
    ghi_chu       text        NULL,                               -- Ghi chú
    stt           integer     NULL,                               -- thứ tự dòng trong request
    nguoi_tao     text        NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_request_nhom_id   ON public.request (nhom_id);
CREATE INDEX IF NOT EXISTS idx_request_ma_vt     ON public.request (ma_vt);
CREATE INDEX IF NOT EXISTS idx_request_thoi_gian ON public.request (thoi_gian);

-- Quyền truy cập cho user đã đăng nhập (giống các bảng khác của app)
ALTER TABLE public.request ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "request_all_authenticated" ON public.request;
CREATE POLICY "request_all_authenticated" ON public.request
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- Realtime (tự làm mới khi người khác thêm/sửa)
DO $$
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.request;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
